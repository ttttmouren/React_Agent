# -*- coding: utf-8 -*-
"""
============================================================================
模块 2（Step 02）：定义 Tool —— 给 Agent 装“手”
============================================================================

【这个模块解决什么问题】
    把“计算差值 / 判断谁更高 / 整理报告”这类【确定性】的活，
    从 LLM 的“嘴”里抽出来，变成【可执行的 Python 代码】。

【为什么需要它】
    模块1我们看到：LLM 会算、会写报告，但它【拿不到数据】，
    而且就算给它数据，它算出来的数字也未必精确可靠。
    Tool = 一段写死的逻辑，给它两个数，差值一定算对。
    LLM 负责“决定什么时候算、算哪个指标”，Tool 负责“算得准”。

【它在整个 Agent 中的位置】
    模块1（大脑）：LLM 自己想
    模块2（手）  ：Tool 能干活          ← 我们现在在这
    模块3（循环）：大脑决定用手，手干完把结果塞回大脑

【和前后模块的关系】
    本模块的 Tool，模块3 的循环会来调用。
    所以 Tool 的【输入/输出】必须设计成“LLM 能填、能读”的形式。
    —— 尤其返回值用【字符串】，因为结果要塞回 messages 给 LLM 看
       （和你模块1练习2塞假消息是同一回事）。
============================================================================
"""

# ---------------------------------------------------------------------------
# 第 0 步：数据源（和模块1一样，只是这次它会被 Tool 真正用到）
# ---------------------------------------------------------------------------
# 注：模块1里这份数据只是“标准答案”用来揭穿 LLM；
#     模块2起，它正式变成 Tool 的【数据源】——Tool 从这里取数。
SAMPLE_BEHAVIOR_DATA = {
    "人物A": {
        "微笑次数": 12,
        "目光接触次数": 25,
        "说话时长秒": 320,
        "打断次数": 2,
        "正向互动次数": 9,
    },
    "人物B": {
        "微笑次数": 5,
        "目光接触次数": 18,
        "说话时长秒": 455,
        "打断次数": 7,
        "正向互动次数": 4,
    },
}

# 所有指标名，抽出来方便 Tool 校验参数（避免 LLM 填错指标名）
METRIC_NAMES = list(next(iter(SAMPLE_BEHAVIOR_DATA.values())).keys())


# ---------------------------------------------------------------------------
# Tool 1：统计计算
# ---------------------------------------------------------------------------
def stat_calc(metric: str, operation: str = "差值") -> str:
    """
    计算人物A和人物B在某项指标上的统计结果。

    参数：
        metric    : 指标名，例如 "微笑次数"
        operation : "差值" / "比例" / "平均值"（默认差值）
    返回：
        一段【文字】结果（注意是字符串，不是数字）。

    ⚠️ 为什么返回字符串而不是数字？
        因为这个结果最终要【塞回 messages 给 LLM 看】，
        LLM 读的是文字，不是 Python 的 float。
        （这点模块3你就明白了——和练习2塞假消息是同一回事。）
    """
    # 1) 先校验指标名合法，不合法直接报错（比让模型拿到 None 再崩好）
    if metric not in METRIC_NAMES:
        return f"错误：没有名为「{metric}」的指标。可选：{METRIC_NAMES}"

    # 2) 从数据源取两个数
    a = SAMPLE_BEHAVIOR_DATA["人物A"][metric]
    b = SAMPLE_BEHAVIOR_DATA["人物B"][metric]

    # 3) 按 operation 分支计算
    if operation == "差值":
        diff = a - b
        who = "人物A" if diff > 0 else ("人物B" if diff < 0 else "两人")
        return f"{metric}：人物A={a}，人物B={b}，差值={diff}（{who}更高）"

    elif operation == "比例":
        if b == 0:  # 除零保护：演示项目的健壮性，顺手养成习惯
            return f"{metric}：人物B为0，无法算比例（人物A={a}）。"
        ratio = round(a / b, 2)  # round 只是把小数收一下，纯 Python 细节
        return f"{metric}：人物A/人物B = {ratio}（即A是B的{ratio}倍）"

    elif operation == "平均值":
        avg = (a + b) / 2
        return f"{metric}：两人平均 = {avg}"
    
    elif operation == "总和":
        sum = a+b
        return f"{metric}：两人总和 = {sum}"

    else:
        return f"错误：不支持的操作「{operation}」。可选：差值/比例/平均值/总和"


# ---------------------------------------------------------------------------
# Tool 2：行为指标分析（按预定义规则判断）
# ---------------------------------------------------------------------------
def analyze_metric(metric: str) -> str:
    """
    根据【简单规则】对某项指标做基础分析。
    注意：这里的规则只是为了演示 Agent 调用工具，不代表任何心理学标准。

    返回一段文字：谁更高、差多少、以及一个简单分类标签。
    """
    if metric not in METRIC_NAMES:
        return f"错误：没有名为「{metric}」的指标。可选：{METRIC_NAMES}"

    a = SAMPLE_BEHAVIOR_DATA["人物A"][metric]
    b = SAMPLE_BEHAVIOR_DATA["人物B"][metric]
    diff = abs(a - b)  # abs 取绝对值，纯 Python 细节

    # 规则1：谁更高
    higher = "人物A" if a > b else ("人物B" if b > a else "持平")

    # 规则2：差异大小分类（演示用的拍脑袋阈值，不是心理学标准）
    if diff == 0:
        level = "无差异"
    elif diff <= 3:
        level = "差异较小"
    elif diff <= 10:
        level = "差异中等"
    else:
        level = "差异明显"

    return (f"【{metric}分析】人物A={a}，人物B={b}，"
            f"更高方={higher}，绝对差={diff}，差异程度={level}。")


# ---------------------------------------------------------------------------
# Tool 3：报告整理
# ---------------------------------------------------------------------------
def build_report() -> str:
    """
    把前面两个 Tool 能算的东西，汇总成一份【适合交给 LLM 的草稿】。
    它不做什么高级分析，只是把数据 + 初步结论摆整齐，
    让 LLM 拿到后只需“润色成报告”，而不是“从头算”。
    """
    lines = ["=== 行为数据互动分析草稿 ===", ""]
    for metric in METRIC_NAMES:
        lines.append(analyze_metric(metric))
    lines.append("")
    lines.append("（以上为自动统计，请据此生成一份两人互动简要报告。）")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# 给 LLM 看的“工具说明书” —— 模块3 会把它整段写进 prompt
# ---------------------------------------------------------------------------
# ⭐ 这是本模块最关键的一个认知：
#    Tool = 函数（干活） + 这段描述（让 LLM 知道有这个工具、怎么用）。
#    模块3 手写 ReAct 循环时，就靠这段文字让 LLM 决定“调哪个、填什么参数”。
TOOL_GUIDE = f"""
你有以下工具可以调用（数据已加载，无需提供原始数据）：
1. stat_calc(metric, operation)：计算两人某项指标的差值/比例/平均值。
2. analyze_metric(metric)：分析某项指标谁更高、差异程度。
3. build_report()：汇总所有指标，生成报告草稿。
指标名(metric)可选：{"/".join(METRIC_NAMES)}。
operation 可选：差值/比例/平均值/总和。
"""


# ---------------------------------------------------------------------------
# 主流程：直接调用 Tool（不经过 LLM），验证“手”能干活
# ---------------------------------------------------------------------------
def main():
    print(">>> 直接调用 Tool（注意：这里还没接 LLM，纯函数自测）\n")

    print("[Tool1 stat_calc] 差值：")
    print("  ", stat_calc("微笑次数", "差值"))
    print("[Tool1 stat_calc] 比例：")
    print("  ", stat_calc("说话时长秒", "比例"))

    print("\n[Tool2 analyze_metric]：")
    print("  ", analyze_metric("目光接触次数"))
    print("  ", analyze_metric("打断次数"))

    print("\n[Tool3 build_report]：")
    print(build_report())

    print("\n>>> 工具说明书（模块3 会喂给 LLM）：")
    print(TOOL_GUIDE)


# Python 标准写法：直接运行时才执行 main()
if __name__ == "__main__":
    main()
