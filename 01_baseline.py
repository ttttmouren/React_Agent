# -*- coding: utf-8 -*-
"""
============================================================================
模块 1（Step 01）：基线 —— 不带任何工具的 LLM，到底能做成什么样？
============================================================================

【这个模块解决什么问题】
    建立一条"对照组"。在引入 Agent / Tool 之前，先亲眼看看：
    一个"裸的" LLM 碰到【需要真实数据】的问题时，会表现成什么样。

【为什么必须要它】
    如果你没看过它失败的样子，后面 Agent 答对了你会觉得"这有什么稀奇"。
    Tool 的价值只有在对比中才看得见。
    这是整个项目最容易被跳过、但最决定你能不能"真懂"的一步。

【它在整个 Agent 中的位置】
    模块1（现在）：  用户问题 ──────────> LLM ──> 回答
                    一条直线，没有回路。这【不是】Agent。

    模块3（目标）：  用户问题 ──> LLM ──> 选Tool ──> 执行 ──┐
                                  ↑                        │
                                  └────── 结果回喂 LLM ─────┘
                    有回路 = 能多步推理 = Agent

【和前后模块的关系】
    本模块是起点，没有前序模块。
    模块 2、3 我会用【完全相同的三个问题】再问一遍。
    到那时你会发现：同样的问题，有没有 Tool，答案是两个世界。

【本模块故意不做 Agent】
    我们就是要先做一个"失败版本"，用它来暴露问题。
============================================================================
"""

import os
from pathlib import Path

from dotenv import load_dotenv
from openai import OpenAI

# ---------------------------------------------------------------------------
# 第 1 步：读入 API Key
# ---------------------------------------------------------------------------
# ⚠️ 这里有个初学者几乎一定会踩的坑，值得重点理解：
#
# load_dotenv() 默认是【从"当前工作目录"找 .env 文件】。
# 但你在 PyCharm 里点右键运行时，"当前工作目录"默认是【项目根目录】
# （对我们来说是 D:\LangChain_Project），而不是脚本所在的
# D:\LangChain_Project\React_Agent。
#
# 结果就是：明明 .env 就在脚本旁边，却读不到，报"Missing credentials"。
#
# 解决办法：不要依赖当前工作目录，改成【用脚本自己的位置】来定位 .env。
#   Path(__file__)            → 当前这个 .py 文件的路径
#   .resolve()                → 转成绝对路径
#   .parent                   → 它所在的文件夹（React_Agent）
#   / ".env"                  → 拼出 React_Agent/.env
#
# 这样无论你从哪里运行、用什么 IDE，都稳稳能找到。这个写法以后可以一直用。
ENV_PATH = Path(__file__).resolve().parent / ".env"
load_dotenv(dotenv_path=ENV_PATH)

# 拿 Key。这是百炼（阿里云）的 key。
API_KEY = os.getenv("DASHSCOPE_API_KEY")

# 加一个明确的检查。
# 为什么要自己检查？因为如果 Key 是空的，openai 库报的错误是
# "Missing credentials..."，新手看到根本不知道是自己 .env 没配。
# 自己先拦一道，能让错误信息直接说人话。
if not API_KEY:
    raise RuntimeError(
        f"没读到 API Key！\n"
        f"我找的文件是：{ENV_PATH}\n"
        f"请确认这个文件存在，并且里面有 DASHSCOPE_API_KEY=sk-xxxx"
    )

# ---------------------------------------------------------------------------
# 第 2 步：创建客户端
# ---------------------------------------------------------------------------
# 这里我们用的是 OpenAI 官方的 Python SDK，但连的是【阿里云百炼】。
#
# 为什么能这样？因为百炼、DeepSeek、智谱这些国内厂商都提供了
# "OpenAI 兼容接口" —— 它们把自家的接口做得和 OpenAI 一模一样。
# 所以你只要改一个 base_url，同一套代码就能跑在不同厂商上。
#
# 这是你 RAG 项目里用过的路子，这次完全一样，不用重新学。
client = OpenAI(
    api_key=API_KEY,

    # base_url 就是"接口地址"。
    # 这一长串是百炼的 OpenAI 兼容模式地址，照抄即可，不用背。
    base_url="https://dashscope.aliyuncs.com/compatible-mode/v1",
)

# 模型名。
# 这里用 qwen3.8-flash：便宜、免费额度更宽松，学习阶段要反复跑很多次，不心疼。
#
# 【怎么知道有哪些模型能选？别翻文档，直接问接口：】
#     models = client.models.list()
#     print([m.id for m in models.data])
# 会打印出当前账号可用的全部模型名（我这台机器上是 251 个）。
# 换成 qwen-plus / qwen-max 也行，改这一行就够了。
MODEL = "qwen3.8-flash"


# ---------------------------------------------------------------------------
# 第 3 步：模拟的"真实数据"
# ---------------------------------------------------------------------------
# 这是一份我们【编造】的模拟行为数据。
#
# 重要说明：
#   - 不涉及任何真实的视频 / 人脸 / 语音识别，那部分以后由别人负责。
#   - 这些数字也【不代表】任何真正的心理学评价标准，纯粹是演示用的假数据。
#
# 在本模块里，这份数据只有一个作用：当"标准答案"，用来揭穿 LLM 的瞎编。
# 到模块 2 时，它会正式变成 Tool 的数据源。
SAMPLE_BEHAVIOR_DATA = {
    "人物A": {
        "微笑次数": 12,
        "目光接触次数": 25,
        "说话时长秒": 320,
        "打断次数": 2,
        "正向互动次数": 9,
    },
    "人物B": {
        "微笑次数": 5,
        "目光接触次数": 18,
        "说话时长秒": 455,
        "打断次数": 7,
        "正向互动次数": 4,
    },
}


# ---------------------------------------------------------------------------
# 第 4 步：一个最朴素的 LLM 调用函数
# ---------------------------------------------------------------------------
def ask_llm(question: str) -> str:
    """
    把问题丢给 LLM，原样返回它的回答。

    这就是"普通 LLM 调用"的全部 —— 一次请求，一次回答，结束。
    注意：它没有任何"查资料"的能力，LLM 只能靠训练时记住的东西回答。
    """
    response = client.chat.completions.create(
        model=MODEL,

        # messages 是对话历史，一个列表，每个元素是一条消息。
        # 每条消息必须有 role（角色）和 content（内容）。
        # 三个常用角色：
        #   system    —— 设定 AI 的人设 / 全局规则，相当于"开场白"
        #   user      —— 用户说的话
        #   assistant —— AI 自己说过的话（多轮对话时才需要）
        messages=[
            {"role": "system", "content": "是一个只会用文言文回答的分析助手。"},
            {"role": "user", "content": question},
        ],

        # temperature 是"随机性旋钮"，取值一般 0~1：
        #   0.0 → 每次回答几乎一样，稳定可复现。做数据分析就该用这个。
        #   0.7 → 更有创造性，但同样输入可能给出不同答案。
        # 后面做 Agent 时也必须保持低温，否则工具调用会飘，极难调试。
        temperature=0.0,
    )

    # 为什么是 choices[0]？
    # 因为接口设计上允许"一次请求让模型生成多个候选答案"（n 参数，默认 1）。
    # 所以返回的是一个 choices 列表，我们只取第一个（也是唯一一个）。
    # .message 是这条候选答案的消息对象，.content 才是真正的文字内容。
    #
    # 【这部分只是 OpenAI 接口的固定结构，记住就行，不用深究为什么这么设计。】
    return response.choices[0].message.content


# ---------------------------------------------------------------------------
# 第 5 步：主流程 —— 问三个"必须有真实数据才能回答"的问题
# ---------------------------------------------------------------------------
def main():
    # 这三个问题的共同点：答案【依赖外部数据】，光靠语言能力猜不出来。
    # 后面模块 2、3 我会原封不动地再问一遍，用来对比。
    questions = [
        "在这次互动中，人物A的微笑次数是多少次？",
        "人物A和人物B相比，谁的说话时间更长？长多少秒？",
        "请分析一下这两个人的互动情况，生成一份简要报告。",

    ]

    for i, q in enumerate(questions, start=1):
        print("=" * 70)
        print(f"问题 {i}: {q}")
        print("-" * 70)

        answer = ask_llm(q)
        print(answer)
        print()

    # -----------------------------------------------------------------------
    # 揭晓真相：把这些问题的"标准答案"打印出来
    # -----------------------------------------------------------------------
    print("=" * 70)
    print("【真相】本次互动的真实数据如下：")
    print("-" * 70)
    for person, metrics in SAMPLE_BEHAVIOR_DATA.items():
        print(f"{person}:")
        for name, value in metrics.items():
            print(f"    {name}: {value}")
        print()

    print("=" * 70)
    print("请回头对比一下：LLM 刚才给的数字，有没有一个是对的？")
    print("=" * 70)


# Python 的标准写法：只有直接运行这个文件时才执行 main()
# （如果别的文件 import 它，就不会自动跑起来）
if __name__ == "__main__":
    main()
